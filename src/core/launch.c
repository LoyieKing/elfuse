#include "shim_blob.h"
#include "syscall/sysvipc.h"

/* The shim code slot in the infra reserve is sized tight (INFRA_SHIM_SLOT, a
 * few x the current blob) so the rest of the reserve goes to the page-table
 * pool. If the shim ever outgrows the slot it would overlap the shim-data
 * block; fail the build loudly rather than corrupt memory at boot. Enlarge
 * INFRA_SHIM_SLOT (and shrink the pool to match) if this fires.
 */
_Static_assert(sizeof(shim_bin) <= INFRA_SHIM_SLOT,
               "shim blob exceeds its infra slot; bump INFRA_SHIM_SLOT");

void launch_destroy_guest(guest_t *g)
{
    /* The pool joins owner pthreads before guest mappings can be removed. */
    if (!proc_exit_group_requested())
        proc_request_exit_group(0);
    thread_wake_all_blocked();
    vcpu_pool_stop();
    if (g->vcpu_valid)
        hv_vcpu_destroy(g->vcpu);
    g->vcpu_valid = false;
    g->vcpu = 0;

    sysvipc_reset();
    guest_destroy(g);
}

int elfuse_launch(const launch_args_t *args)
{
    extern char **environ;
    char **envp_use = args->envp ? args->envp : environ;
    profile_init();

    guest_t g;
    bool guest_initialized = false;
    guest_bootstrap_t boot;

    /* Local copy of the temp flag (ownership contract in launch.h): the
     * caller's launch_args_t is const, and the flag must drop once the unlink
     * happens.
     */
    bool elf_host_temp = args->elf_host_temp;

    /* The guest-visible entrypoint path is argv[0]; elf_path is the resolved
     * host path to that binary. They differ when path translation or a
     * FUSE-materialized temp is involved.
     */
    const char *elf_guest_path = (args->guest_argc > 0 && args->guest_argv)
                                     ? args->guest_argv[0]
                                     : args->elf_path;

    /* uid_is_permitted() grants every setuid under fakeroot because fakeroot
     * starts the guest as uid/gid 0. A non-root --user keeps that grant while
     * reporting an unprivileged uid, so the guest could call setuid(0).
     */
    if (proc_fakeroot_enabled() && args->has_creds &&
        (args->uid != 0 || args->gid != 0)) {
        log_error(
            "--fakeroot runs the guest as uid/gid 0 and cannot be combined "
            "with --user %u:%u",
            args->uid, args->gid);
        goto fail;
    }

    /* Stage --user before bring-up; proc.h states why it cannot be applied
     * afterwards.
     */
    if (args->has_creds)
        proc_set_initial_ids(args->uid, args->gid);
    if (proc_preempt_init() < 0)
        goto fail;
    profile_start_writer();

    if (guest_bootstrap_prepare(&g, args->elf_path, elf_host_temp,
                                elf_guest_path, args->sysroot, args->guest_argc,
                                args->guest_argv, envp_use, shim_bin,
                                shim_bin_len, args->verbose, args->memory_mode,
                                args->rss_mode, &guest_initialized, &boot) < 0)
        goto fail;

    /* A FUSE-materialized temp has been loaded; drop it once the guest has its
     * own mapping, unless Rosetta still needs the reopenable host path.
     */
    if (elf_host_temp && !g.is_rosetta) {
        unlink(args->elf_path);
        elf_host_temp = false;
    }

    /* Reject GDB for a Rosetta (x86_64) guest here, not just in main(): the
     * stub exposes the aarch64 shim's register/memory view, which is the wrong
     * architecture for a Rosetta-translated x86_64 guest. main() rejects it up
     * front via a static ELF probe, but enforcing it in elfuse_launch (once
     * bring-up has set g.is_rosetta) makes every caller inherit the constraint.
     */
    if (args->gdb_port > 0 && g.is_rosetta) {
        log_error(LAUNCH_GDB_X86_64_MSG);
        goto fail;
    }

    if (args->sysroot) {
        bool case_sensitive = true;
        bool case_preserving = true;
        if (sysroot_probe_case_sensitivity(args->sysroot, &case_sensitive,
                                           &case_preserving) == 0)
            proc_set_sysroot_casefold(case_preserving && !case_sensitive);
        else
            proc_set_sysroot_casefold(false);
    } else {
        proc_set_sysroot_casefold(false);
    }

    /* Placed after the casefold probe so path_translate_at() sees the sysroot's
     * real case behavior.
     */
    if (args->cwd_guest && args->cwd_guest[0] != '\0') {
        path_translation_t tx;
        if (path_translate_at(LINUX_AT_FDCWD, args->cwd_guest, PATH_TR_NONE,
                              &tx) < 0) {
            log_error("failed to resolve working directory %s: %s",
                      args->cwd_guest, strerror(errno));
            goto fail;
        }

        /* A shm leaf needs sys_chdir's O_NOFOLLOW fd and virtual-cwd publish;
         * entering it here would add a holder of the never-follow invariant
         * dev_shm_resolve_path() enumerates. Refuse instead.
         */
        if (tx.is_dev_shm) {
            log_error("--workdir %s: /dev/shm is not supported",
                      args->cwd_guest);
            goto fail;
        }

        /* proc_resolve_sysroot_path() falls back to the host spelling for a
         * path the sysroot does not hold, which would start the guest in a
         * same-named host directory outside the tree --workdir named.
         */
        if (args->sysroot) {
            char sr[LINUX_PATH_MAX];
            if (!proc_sysroot_snapshot(sr, sizeof(sr))) {
                log_error("failed to read the sysroot prefix for --workdir %s",
                          args->cwd_guest);
                goto fail;
            }

            /* Same carve-out as path_dirent_dir_holds_escapes(): "--sysroot /"
             * owns every host path, but path_prefix_match on a bare separator
             * accepts "/" alone.
             */
            size_t srlen = strlen(sr);
            if (srlen > 1 && !path_prefix_match(tx.host_path, sr, srlen)) {
                log_error("--workdir %s does not resolve inside the sysroot",
                          args->cwd_guest);
                goto fail;
            }
        }
        if (chdir(tx.host_path) < 0) {
            log_error("failed to set working directory %s: %s", args->cwd_guest,
                      strerror(errno));
            goto fail;
        }
        if (proc_cwd_refresh() < 0)
            proc_cwd_invalidate();
    }

    hv_vcpu_t vcpu;
    hv_vcpu_exit_t *vexit;
    if (guest_bootstrap_create_vcpu(&g, &boot, args->verbose, &vcpu, &vexit) <
        0)
        goto fail;

    /* Adopt the bootstrap vCPU as CPU 0; other workers start on demand. */
    if (vcpu_pool_start_with_main(&g, vcpu, vexit, args->verbose) != 0) {
        log_error("failed to start vCPU worker pool");
        goto fail;
    }

    /* GDB setup must happen before the first run so entry-stop and hardware
     * breakpoints can affect the initial vCPU.
     */
    if (args->gdb_port > 0) {
        if (gdb_stub_init(args->gdb_port, &g) < 0) {
            log_error("failed to initialize GDB stub");
            goto fail;
        }
        gdb_stub_sync_debug_regs(vcpu);
        if (args->gdb_stop_on_entry)
            gdb_stub_wait_for_attach();
    }

    /* Slot-0 worker loop (this thread) owns guest execution until exit, fatal
     * signal, or timeout.
     */
    int exit_code = vcpu_pool_run_main(args->timeout_sec);

    /* Tear down debugger state before joining workers: a worker parked in
     * gdb_stub_handle_stop() stays active (not deactivated) until this
     * broadcasts resume_cond, so joining first would just time out and detach
     * it while it is still paused.
     */
    gdb_stub_shutdown();

    /* Stop execution before diagnostics read the still-mapped guest state. */
    if (!proc_exit_group_requested())
        proc_request_exit_group(0);
    thread_wake_all_blocked();
    vcpu_pool_stop();

    /* Diagnostic counter dump runs before guest_destroy so the shim_data
     * mapping is still valid. ELFUSE_SHIM_STATS is the gate; an unset variable
     * produces no output.
     */
    if (shim_globals_stats_enabled())
        shim_globals_counters_dump(&g);

    /* Dump the startup histogram before guest_destroy so any cleanup-path
     * syscalls (closing host fds, unmapping the slab) do not appear in the
     * captured set. The dump is a no-op when ELFUSE_STARTUP_TRACE=syscalls was
     * not requested.
     */
    syscall_hist_dump();

    /* Give back any pty slaves this process still holds before the guest
     * teardown below. The guest's stdio slaves are closed by the kernel, not by
     * the guest, so they never pass through the per-fd close hook; a master in
     * another process would otherwise wait forever for a hangup this exit
     * should have produced. Bring-up failures skip this: the fail path is only
     * reachable before the run loop, so no slave exists yet.
     */
    proc_pty_release_process_slaves();

    if (guest_initialized)
        launch_destroy_guest(&g);

    /* Rosetta guests keep the FUSE-materialized temp alive for the whole run
     * (the translator reopens the host path); drop it now that the guest is
     * gone so repeated Rosetta launches do not accumulate temp files.
     */
    if (elf_host_temp)
        unlink(args->elf_path);

    return exit_code;

fail:
    /* Bring-up failed: unwind whatever exists so far, including the temp unlink
     * this side owns past the prepare call (contract in launch.h). Staged
     * --user credentials are dropped too (proc.h).
     */
    proc_clear_initial_ids();
    if (guest_initialized)
        launch_destroy_guest(&g);
    if (elf_host_temp)
        unlink(args->elf_path);
    return 1;
}
